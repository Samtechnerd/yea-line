"""Draw the Yea-Line screensaver picture for the phone (the logo on a dark blue gradient, 3:5 like the MP50's screen).
Writes yea_picture.py, which holds the JPEG as base64 so it is built into the program."""
import base64
import io
import os

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
W, H = 576, 960


def main():
    logo = Image.open(os.path.join(HERE, "yealine_logo.png")).convert("RGBA")
    bg = Image.new("RGB", (W, H))
    d = ImageDraw.Draw(bg)
    for y in range(H):
        t = y / H
        d.line([(0, y), (W, y)], fill=(int(14 + 10 * t), int(22 + 30 * t), int(48 + 50 * t)))
    size = 400
    logo = logo.resize((size, size), Image.LANCZOS)
    bg.paste(logo, ((W - size) // 2, 220), logo)
    try:
        font = ImageFont.truetype("segoeui.ttf", 68)
    except OSError:
        font = ImageFont.load_default()
    text = "Yea-Line"
    w = d.textlength(text, font=font)
    d.text(((W - w) / 2, 680), text, fill=(235, 240, 250), font=font)
    buf = io.BytesIO()
    bg.save(buf, "JPEG", quality=88)
    with open(os.path.join(HERE, "yea_picture.py"), "w", encoding="utf-8", newline="\n") as f:
        f.write('"""Generated by make_saver.py: the Yea-Line screensaver picture (JPEG, base64)."""\n')
        f.write("JPEG_B64 = (\n")
        b64 = base64.b64encode(buf.getvalue()).decode()
        for i in range(0, len(b64), 100):
            f.write(f'    "{b64[i:i + 100]}"\n')
        f.write(")\n")
    print("yea_picture.py:", len(buf.getvalue()), "bytes of JPEG")


if __name__ == "__main__":
    main()
